// Exports kit rules as a single instruction file for other AI tools (AGENTS.md, CLAUDE.md, Copilot).
import fs from 'node:fs';
import path from 'node:path';
import { KIT_DIR } from './installer.mjs';

const TARGET_FILES = {
  'agents-md': 'AGENTS.md',
  claude: 'CLAUDE.md',
  copilot: '.github/copilot-instructions.md',
};

export function exportInstructions(targetDir, { format = 'agents-md', force = false, dryRun = false } = {}) {
  const rel = TARGET_FILES[format];
  if (!rel) throw new Error(`Unknown export format "${format}". Use: ${Object.keys(TARGET_FILES).join(', ')}`);

  targetDir = path.resolve(targetDir);
  const dest = path.join(targetDir, rel);
  if (fs.existsSync(dest) && !force) {
    throw new Error(`${rel} already exists. Use --force to overwrite.`);
  }

  const rulesDir = path.join(KIT_DIR, '.agents', 'rules');
  const parts = fs.readdirSync(rulesDir)
    .filter((f) => f.endsWith('.md'))
    .sort()
    .map((f) => fs.readFileSync(path.join(rulesDir, f), 'utf8').replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n?/, '').trim());

  const content = [
    '<!-- Generated by agy-toolkit (agk export). Edit source rules in the toolkit repo. -->',
    '',
    ...parts.flatMap((p) => [p, '']),
  ].join('\n');

  if (!dryRun) {
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, content);
  }
  return { dest, rel, format, bytes: Buffer.byteLength(content), dryRun };
}
